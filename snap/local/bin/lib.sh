#!/bin/bash
# Shared helpers for the fluxer-server snap. Sourced by hooks and services.

export PATH="$SNAP/opt/node/bin:$SNAP/usr/bin:$SNAP/bin:$SNAP/usr/sbin:$SNAP/sbin:$PATH"
triplet="${SNAP_LAUNCHER_ARCH_TRIPLET:-$(uname -m)-linux-gnu}"
export LD_LIBRARY_PATH="$SNAP/opt/native/lib:$SNAP/usr/lib/$triplet:$SNAP/lib/$triplet:$SNAP/usr/lib/postgresql/18/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
export SSL_CERT_FILE="${SSL_CERT_FILE:-$SNAP/etc/ssl/certs/ca-certificates.crt}"

PG_BIN="$SNAP/usr/lib/postgresql/18/bin"
FLUXER_HOME="$SNAP/opt/fluxer"
STATE="$SNAP_COMMON"
SECRETS_FILE="$STATE/secrets.env"
ENV_FILE="$STATE/fluxer.env"

# Loopback ports used between the bundled services.
PORT_POSTGRES=15432
PORT_VALKEY=16379
PORT_NATS=14222
PORT_NATS_HTTP=18222
PORT_MEILI=17700
PORT_SEAWEED_MASTER=19333
PORT_SEAWEED_VOLUME=18380
PORT_SEAWEED_FILER=18888
PORT_SEAWEED_S3=18333
PORT_LIVEKIT=17880
PORT_API=18080
PORT_GATEWAY=18771
PORT_GATEWAY_DIST=18081
PORT_MEDIA=18082
PORT_APP_PROXY=18773
PORT_ADMIN=13020
PORT_PUSH=18126
PORT_DISCOVERY=18088

die() {
    echo "fluxer-server: $*" >&2
    exit 1
}

# Single-quote a value for safe use in a sourced shell file.
shquote() {
    printf "'%s'" "${1//\'/\'\\\'\'}"
}

rand_hex() {
    openssl rand -hex 32
}

gen_secret() {
    # gen_secret NAME VALUE: add NAME to the secrets file unless it exists.
    grep -q "^$1=" "$SECRETS_FILE" 2>/dev/null || printf '%s=%s\n' "$1" "$2" >> "$SECRETS_FILE"
}

ensure_secrets() {
    mkdir -p "$STATE"
    touch "$SECRETS_FILE"
    chmod 600 "$SECRETS_FILE"
    local name
    for name in POSTGRES_PASSWORD MEILI_MASTER_KEY FLUXER_S3_SECRET_KEY FLUXER_SUDO_MODE_SECRET \
        FLUXER_CONNECTION_INITIATION_SECRET FLUXER_PROFILE_PSEUDONYM_SECRET FLUXER_GATEWAY_RPC_AUTH_TOKEN \
        FLUXER_ERLANG_COOKIE FLUXER_MEDIA_PROXY_SECRET_KEY FLUXER_ADMIN_SECRET_KEY_BASE \
        FLUXER_ADMIN_OAUTH_CLIENT_SECRET LIVEKIT_API_SECRET FLUXER_SETUP_TOKEN; do
        grep -q "^$name=" "$SECRETS_FILE" || gen_secret "$name" "$(rand_hex)"
    done
    grep -q '^FLUXER_MEDIA_PROXY_UPLOAD_RELAY_SECRET_BASE64=' "$SECRETS_FILE" ||
        gen_secret FLUXER_MEDIA_PROXY_UPLOAD_RELAY_SECRET_BASE64 "$(openssl rand -base64 32)"
    grep -q '^FLUXER_ACTIVITYPUB_SIGNING_KEY_BASE64=' "$SECRETS_FILE" ||
        gen_secret FLUXER_ACTIVITYPUB_SIGNING_KEY_BASE64 \
            "$(openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:2048 -outform DER | base64 -w0)"
    if ! grep -q '^FLUXER_VAPID_PUBLIC_KEY=' "$SECRETS_FILE"; then
        local key
        key="$(openssl ecparam -name prime256v1 -genkey -noout)"
        gen_secret FLUXER_VAPID_PUBLIC_KEY \
            "$(printf '%s' "$key" | openssl ec -pubout -outform DER 2>/dev/null | tail -c 65 | base64 -w0 | tr '/+' '_-' | tr -d '=')"
        gen_secret FLUXER_VAPID_PRIVATE_KEY \
            "$(printf '%s' "$key" | openssl ec -outform DER 2>/dev/null | tail -c +8 | head -c 32 | base64 -w0 | tr '/+' '_-' | tr -d '=')"
    fi
    gen_secret LIVEKIT_API_KEY fluxer
    gen_secret FLUXER_S3_ACCESS_KEY fluxer
}

# Render $ENV_FILE from the snap configuration and the generated secrets.
render_env() {
    ensure_secrets

    local domain proxy http_port https_port tls node_ip
    domain="$(snapctl get domain)"
    proxy="$(snapctl get behind-proxy)"
    http_port="$(snapctl get http-port)"
    https_port="$(snapctl get https-port)"
    tls="$(snapctl get tls)"
    node_ip="$(snapctl get livekit-node-ip)"
    http_port="${http_port:-80}"
    https_port="${https_port:-443}"

    local scheme=https public_port="$https_port" origin
    if [ -n "$proxy" ]; then
        public_port=443
    fi
    origin="$scheme://$domain"
    [ "$public_port" = 443 ] || origin="$origin:$public_port"

    local site global bind=""
    global="admin off"
    if [ -n "$proxy" ]; then
        site="http://$domain:${proxy##*:}"
        bind="bind ${proxy%:*}"
        global="$global
	auto_https off"
    else
        site="https://$domain"
        global="$global
	http_port $http_port
	https_port $https_port"
    fi

    local tmp="$ENV_FILE.tmp"
    {
        echo "# Generated by the configure hook. Do not edit."
        set -a
        # shellcheck disable=SC1090
        . "$SECRETS_FILE"
        set +a
        while IFS= read -r line; do
            printf 'export %s\n' "${line%%=*}=$(shquote "${line#*=}")"
        done < "$SECRETS_FILE"

        local -A v=(
            [FLUXER_ENV]=production
            [NODE_ENV]=production
            [FLUXER_SELF_HOSTED]=true
            [FLUXER_BASE_DOMAIN]="$domain"
            [FLUXER_DOMAIN]="$domain"
            [FLUXER_PUBLIC_SCHEME]="$scheme"
            [FLUXER_PUBLIC_PORT]="$public_port"
            [FLUXER_PUBLIC_ORIGIN]="$origin"
            [FLUXER_TRUST_CLIENT_IP_HEADER]=true
            [FLUXER_APP_ENDPOINT]="$origin"
            [FLUXER_MEDIA_ENDPOINT]="$origin/media"
            [FLUXER_MEDIA_PROXY_PUBLIC_ENDPOINT]="$origin/media"
            [FLUXER_ADMIN_ENDPOINT]="$origin/admin"
            [FLUXER_MARKETING_ENDPOINT]="$origin"
            [FLUXER_STATIC_CDN_ENDPOINT]="$origin"
            [FLUXER_ADMIN_BASE_PATH]=/admin
            [FLUXER_DATABASE_BACKEND]=postgres
            [FLUXER_POSTGRES_HOST]=127.0.0.1
            [FLUXER_POSTGRES_PORT]="$PORT_POSTGRES"
            [FLUXER_POSTGRES_DATABASE]=fluxer
            [FLUXER_POSTGRES_USERNAME]=fluxer
            [FLUXER_POSTGRES_PASSWORD]="$POSTGRES_PASSWORD"
            [FLUXER_POSTGRES_SSL]=false
            [FLUXER_KV_URL]="redis://127.0.0.1:$PORT_VALKEY/0"
            [FLUXER_NATS_URL]="nats://127.0.0.1:$PORT_NATS"
            [FLUXER_NATS_JETSTREAM_URL]="nats://127.0.0.1:$PORT_NATS"
            [FLUXER_SVC_NATS_URL]="nats://127.0.0.1:$PORT_NATS"
            [FLUXER_SVC_SHARD_COUNT]=1
            [FLUXER_SEARCH_ENGINE]=meilisearch
            [FLUXER_SEARCH_URL]="http://127.0.0.1:$PORT_MEILI"
            [FLUXER_SEARCH_API_KEY]="$MEILI_MASTER_KEY"
            [FLUXER_S3_ENDPOINT]="http://127.0.0.1:$PORT_SEAWEED_S3"
            [FLUXER_S3_PUBLIC_ENDPOINT]="http://127.0.0.1:$PORT_SEAWEED_S3"
            [FLUXER_S3_REGION]=us-east-1
            [FLUXER_S3_ACCESS_KEY_ID]="$FLUXER_S3_ACCESS_KEY"
            [FLUXER_S3_SECRET_ACCESS_KEY]="$FLUXER_S3_SECRET_KEY"
            [FLUXER_S3_FORCE_PATH_STYLE]=true
            [FLUXER_S3_BUCKET_CDN]=fluxer
            [FLUXER_S3_BUCKET_UPLOADS]=fluxer-uploads
            [FLUXER_S3_BUCKET_REPORTS]=fluxer-reports
            [FLUXER_S3_BUCKET_HARVESTS]=fluxer-harvests
            [FLUXER_API_PRESIGNED_ATTACHMENT_UPLOADS_ENABLED]=true
            [FLUXER_API_PRESIGNED_HARVEST_DOWNLOADS_ENABLED]=false
            [FLUXER_LIVEKIT_ENABLED]=true
            [FLUXER_LIVEKIT_BUNDLED]=true
            [FLUXER_LIVEKIT_API_KEY]="$LIVEKIT_API_KEY"
            [FLUXER_LIVEKIT_API_SECRET]="$LIVEKIT_API_SECRET"
            [FLUXER_LIVEKIT_INTERNAL_URL]="http://127.0.0.1:$PORT_LIVEKIT"
            [FLUXER_LIVEKIT_URL]="$origin/livekit"
            [FLUXER_LIVEKIT_DEFAULT_REGION]='{"id":"default","name":"Default","emoji":"🌍","latitude":0,"longitude":0}'
            [FLUXER_LIVEKIT_TURN_SERVERS]='[]'
            [FLUXER_EMAIL_FROM_EMAIL]="noreply@$domain"
            [FLUXER_VAPID_EMAIL]="admin@$domain"
            [FLUXER_PASSKEY_RP_ID]="$domain"
            [FLUXER_PASSKEY_ADDITIONAL_ALLOWED_ORIGINS]="$origin"
            [FLUXER_INTERNAL_API_ENDPOINT]="http://127.0.0.1:$PORT_API"
            [FLUXER_INTERNAL_MEDIA_PROXY_ENDPOINT]="http://127.0.0.1:$PORT_MEDIA"
            [FLUXER_MEDIA_PROXY_UPLOAD_RELAY_ENDPOINT]="$origin/media"
            [FLUXER_NODE_EXTRA_CA_CERTS]="$SSL_CERT_FILE"
            [NODE_EXTRA_CA_CERTS]="$SSL_CERT_FILE"
            [AWS_EC2_METADATA_DISABLED]=true
            [LIVEKIT_NODE_IP]="$node_ip"
            [LIVEKIT_TCP_PORT]=7881
            [LIVEKIT_UDP_PORT]=7882
            [EDGE_SITE_ADDRESS]="$site"
            [EDGE_BIND]="$bind"
            [EDGE_GLOBAL_OPTIONS]="$global"
            [EDGE_TLS_DIRECTIVE]="${tls:+tls $tls}"
        )
        local k
        for k in "${!v[@]}"; do
            printf 'export %s=%s\n' "$k" "$(shquote "${v[$k]}")"
        done

        # User overrides: snap set fluxer-server env.NAME=value
        local name
        while IFS=$'\t' read -r name val; do
            [[ "$name" =~ ^[A-Za-z_][A-Za-z0-9_]*$ ]] || continue
            printf 'export %s=%s\n' "$name" "$(shquote "$val")"
        done < <(snapctl get env -d 2>/dev/null | jq -r '(.env // {}) | to_entries[] | [.key, (.value|tostring)] | @tsv')
    } > "$tmp"
    chmod 600 "$tmp"
    mv "$tmp" "$ENV_FILE"
}

load_env() {
    [ -f "$ENV_FILE" ] || die "not configured yet: snap set fluxer-server domain=<your domain>"
    set -a
    # shellcheck disable=SC1090
    . "$ENV_FILE"
    set +a
}

mark_ready() { mkdir -p "$STATE/run"; touch "$STATE/run/$1.ready"; }
clear_ready() { rm -f "$STATE/run/$1.ready"; }

wait_port() {
    # wait_port PORT [NAME]
    local i
    for i in $(seq 1 300); do
        (exec 3<>"/dev/tcp/127.0.0.1/$1") 2>/dev/null && return 0
        sleep 1
    done
    die "timed out waiting for ${2:-port $1}"
}

wait_ready() {
    local i
    for i in $(seq 1 300); do
        [ -e "$STATE/run/$1.ready" ] && return 0
        sleep 1
    done
    die "timed out waiting for $1"
}

# Run a command as the unprivileged snap_daemon user.
as_daemon() {
    exec setpriv --reuid snap_daemon --regid snap_daemon --clear-groups "$@"
}
